"""Outbound ports; adapters implement them structurally."""

from typing import Protocol, runtime_checkable

from .album import Album
from .identifiers import ISRC, TrackId, PlaylistId
from .catalog import Track, PlatformAlbum
from .recording import Candidate, Recording


@runtime_checkable
class Platform(Protocol):
    def search_tracks(self, query: str, limit: int = 25) -> list[Track]: ...
    def track_by_isrc(self, isrc: ISRC) -> Track | None: ...
    def create_playlist(self, name: str, description: str = "") -> PlaylistId: ...
    def add_tracks(self, playlist: PlaylistId, tracks: list[TrackId]) -> None: ...
    def search_albums(self, query: str, limit: int = 25) -> list[PlatformAlbum]: ...
    def album_tracks(self, album_id: TrackId) -> list[Track]: ...
    def album_editions(self, album_id: TrackId) -> list[PlatformAlbum]: ...
    # All sibling editions of the given album (same release, different pressings) — e.g. via the artist's discography.
    def playlist_tracks(self, playlist: PlaylistId) -> list[Track]: ...
    # The full current track list of an existing platform playlist (paginated internally).


@runtime_checkable
class MetadataProvider(Protocol):
    def recordings_for(self, candidate: Candidate) -> list[Recording]: ...
    def albums_for(self, candidate: Candidate) -> list[Album]: ...
